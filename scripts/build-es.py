#!/usr/bin/env python3
"""Generate es/index.html (Spanish, indexable) from index.html. Run after every edit to index.html."""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
src = (ROOT / "index.html").read_text(encoding="utf-8")

TITLE = "Esteban Triviño — Desarrollador iOS Senior (Swift, SwiftUI, TCA) · Colombia · Remoto"
DESC = ("Esteban Triviño (Esteban Trivino) — Desarrollador iOS Senior e Ingeniero de Software en Colombia, disponible remoto. "
        "9 años en software, 5 en iOS: Swift, SwiftUI, TCA, Combine, VIPER, MVVM. Fintech y billeteras digitales para "
        "Latinoamérica, con ingeniería aumentada por IA (Claude Code y GitHub Copilot).")
OG_DESC = ("Desarrollador iOS Senior e Ingeniero de Software · Swift · SwiftUI · TCA · Fintech y billeteras digitales · "
           "Ingeniería aumentada con IA. Colombia · Remoto.")

def sub(pattern, repl, text):
    out, n = re.subn(pattern, lambda m: repl, text, count=1)
    if n != 1:
        raise SystemExit(f"pattern not found: {pattern}")
    return out

h = src
h = sub(r'<html lang="en"', '<html lang="es"', h)
h = sub(r"<title>.*?</title>", f"<title>{TITLE}</title>", h)
h = sub(r'<meta name="description" content="[^"]*" />', f'<meta name="description" content="{DESC}" />', h)
h = sub(r'<link rel="canonical" href="[^"]*" />', '<link rel="canonical" href="https://estebantrivino.com/es/" />', h)
h = sub(r'<meta property="og:url" content="[^"]*" />', '<meta property="og:url" content="https://estebantrivino.com/es/" />', h)
h = sub(r'<meta property="og:title" content="[^"]*" />', '<meta property="og:title" content="Esteban Triviño — Desarrollador iOS Senior" />', h)
h = sub(r'<meta property="og:description" content="[^"]*" />', f'<meta property="og:description" content="{OG_DESC.replace("&", "&amp;")}" />', h)
h = h.replace("https://estebantrivino.com/og-image.png", "https://estebantrivino.com/og-image-es.png")
h = sub(r'<meta property="og:image:alt" content="[^"]*" />', '<meta property="og:image:alt" content="Esteban Triviño — Desarrollador iOS Senior e Ingeniero de Software" />', h)
h = sub(r'<meta property="og:locale" content="en_US" />\n  <meta property="og:locale:alternate" content="es_CO" />',
        '<meta property="og:locale" content="es_CO" />\n  <meta property="og:locale:alternate" content="en_US" />', h)
h = sub(r'<meta name="twitter:title" content="[^"]*" />', '<meta name="twitter:title" content="Esteban Triviño — Desarrollador iOS Senior" />', h)
h = sub(r'<meta name="twitter:description" content="[^"]*" />', '<meta name="twitter:description" content="Desarrollador iOS Senior e Ingeniero de Software · Swift · SwiftUI · TCA · Ingeniería aumentada con IA." />', h)
# ProfilePage node for the Spanish URL
h = sub(r'"@id": "https://estebantrivino.com/#profile",\n      "url": "https://estebantrivino.com/",\n      "name": "[^"]*",\n      "inLanguage": "en"',
        f'"@id": "https://estebantrivino.com/es/#profile",\n      "url": "https://estebantrivino.com/es/",\n      "name": "{TITLE}",\n      "inLanguage": "es"', h)
h = h.replace("<!DOCTYPE html>", "<!DOCTYPE html>\n<!-- GENERATED by scripts/build-es.py from /index.html — do not edit by hand. -->", 1)

(ROOT / "es").mkdir(exist_ok=True)
(ROOT / "es" / "index.html").write_text(h, encoding="utf-8")
print("es/index.html written")
